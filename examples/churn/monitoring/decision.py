"""Stage 4 - the retraining decision (Module 14).

    python -m monitoring.decision

Reads drift_report.json + performance_report.json and applies an explicit
policy matrix. A human reviews the recommendation; the script never retrains
by itself. Writes monitoring/decision.md.

    drift?      degraded?     action
    ------------------------------------------------------------
    no          no            KEEP - nothing to do
    yes         no            MONITOR - drift is not proof; re-wait
    no          yes           INVESTIGATE - labels/pipeline bug, not drift
    yes         yes           RETRAIN CANDIDATE - human review required

Also states the rollback path before anything is promoted: the registry can
always return production to the previous version (Module 09).
"""

from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
MON = ROOT / "monitoring"
DRIFT = MON / "drift_report.json"
PERF = MON / "performance_report.json"
DECISION = MON / "decision.md"

ACTIONS = {
    (False, False): "KEEP",
    (True, False): "MONITOR",
    (False, True): "INVESTIGATE",
    (True, True): "RETRAIN CANDIDATE",
}

WHY = {
    "KEEP": "Inputs look like training data and measured performance is "
            "within tolerance. Continue routine monitoring.",
    "MONITOR": "Distribution moved but measured performance has NOT dropped. "
               "Drift alone is not evidence of a bad model - retrain only "
               "after labels show degradation (or drift persists and "
               "degrades later).",
    "INVESTIGATE": "Performance dropped WITHOUT input drift. Drift detection "
                   "cannot explain this: check labelling delays, a pipeline "
                   "bug, leakage, or a metric mistake before retraining.",
    "RETRAIN CANDIDATE": "Drift AND measured degradation agree. Prepare a "
                         "retrained candidate, run the full pipeline and "
                         "gates (Module 08), register it (Module 09), and "
                         "promote only after review.",
}


def main() -> int:
    for path in (DRIFT, PERF):
        if not path.exists():
            raise SystemExit(
                f"missing {path.name} - run monitoring.drift and "
                f"monitoring.performance first"
            )

    drift = json.loads(DRIFT.read_text(encoding="utf-8"))
    perf = json.loads(PERF.read_text(encoding="utf-8"))

    drifted = drift["overall"] in ("DRIFT DETECTED", "moderate drift")
    degraded_scenarios = [s for s in perf["scenarios"] if s["degraded"]]
    # evaluate the most recent window: the latest scenario alphabetically is
    # not meaningful, so prefer the last entry in the report order
    latest = perf["scenarios"][-1]
    degraded = bool(latest["degraded"])

    action = ACTIONS[(drifted, degraded)]

    lines = [
        "# Monitoring decision",
        "",
        "| input | value |",
        "|---|---|",
        f"| drift overall | {drift['overall']} |",
        f"| strong drift features | {', '.join(drift['strong']) or 'none'} |",
        f"| latest window | {latest['scenario']} |",
        f"| latest roc_auc | {latest['roc_auc']} (floor {latest['floor']}) |",
        f"| degraded windows | {len(degraded_scenarios)} |",
        "",
        f"## Decision: **{action}**",
        "",
        WHY[action],
        "",
        "## Human review checklist",
        "",
        "- [ ] I read the drift report and know WHICH features moved.",
        "- [ ] I read the performance report and know WHETHER labels agree.",
        ("- [ ] If retraining: run `python -m pipe.run --clean` and confirm "
         "the quality gate passes."),
        "- [ ] Register the candidate: `python -m registry register ...`.",
        ("- [ ] Know the way back BEFORE promoting: "
         "`python -m registry rollback production`."),
        "",
        ("_Generated by monitoring/decision.py. A script recommends; "
         "a human decides._"),
    ]
    DECISION.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"drift={drift['overall']!r}  latest_window={latest['scenario']!r}  "
          f"degraded={degraded}")
    print(f"decision: {action}")
    print("-> monitoring/decision.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())